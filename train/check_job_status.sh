#!/bin/bash
# 查看SLURM作业状态的便捷脚本

# 如果提供了作业ID，显示该作业的详细信息
if [ -n "$1" ]; then
    JOBID=$1
    echo "=========================================="
    echo "作业ID: $JOBID 的详细信息"
    echo "=========================================="
    scontrol show job $JOBID
    echo ""
    echo "=========================================="
    echo "预计开始时间和其他信息"
    echo "=========================================="
    squeue -j $JOBID --format="%.18i %.9P %.20j %.8u %.2t %.10M %.6D %R %.20S"
else
    # 如果没有提供作业ID，显示用户的所有作业
    echo "=========================================="
    echo "你的所有作业"
    echo "=========================================="
    squeue -u $(whoami) --format="%.18i %.9P %.20j %.8u %.2t %.10M %.6D %R %.20S"
    echo ""
    echo "=========================================="
    echo "最近提交的作业ID"
    echo "=========================================="
    echo "使用以下命令查看详细信息："
    echo "  bash train/check_job_status.sh JOBID"
    echo "  scontrol show job JOBID"
fi

